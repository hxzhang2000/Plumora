/* ============================================================
 * 汉字判定 —— 与笔画表（strokes.ts）的收字域同一口径
 *
 * 为什么单独一个文件：笔画表底座是 27,584 字的生成物（gzip 约 88KB），
 * 而「是不是汉字」这件判定只需要一条正则。两者放在同一模块里，
 * 任何只想做判定的调用方（如起卦页的输入即时校验）都会被强制拖上整张表。
 *
 * 收字域 = CJK 统一表意文字基本区（U+4E00–U+9FFF）+ 扩展 A（U+3400–U+4DBF），
 * 与 scripts/build-strokes.mjs 生成底座时的域一致；域内逐字有值，
 * 域外一律视为非汉字（03 文档 §6.4：不猜测、不静默兜底）。
 * ============================================================ */

/** 是否为汉字（CJK 统一表意文字基本区 + 扩展 A） */
export function isHanChar(ch: string): boolean {
  return /^[\u3400-\u4DBF\u4E00-\u9FFF]$/.test(ch);
}
